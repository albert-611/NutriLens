/**
 * Searches the local verified food catalog by query string and optional category/preparation.
 */
export function searchFoods(
  query: string,
  options?: {
    category?: string;
    preparationState?: PreparationState;
    limit?: number;
  }
): FoodSearchResultItem[] {
  const q = (query || '').trim().toLowerCase();
  if (!q) return [];

  const limit = options?.limit ?? 15;
  const filtered = FOOD_CATALOG.filter((f) => {
    if (options?.category && f.category !== options.category) return false;
    if (options?.preparationState && f.preparation_state !== options.preparationState) return false;

    // Match canonical name, english name, bangla name, or any alias
    if (f.canonical_name.toLowerCase().includes(q)) return true;
    if (f.name_en.toLowerCase().includes(q)) return true;
    if (f.name_bn.toLowerCase().includes(q)) return true;
    return f.aliases.some((alias) => alias.toLowerCase().includes(q));
  });

  return filtered.slice(0, limit).map((f) => ({
    food_id: f.id,
    canonical_name: f.canonical_name,
    local_name: f.name_en,
    local_name_bn: f.name_bn,
    category: f.category,
    preparation_state: f.preparation_state,
    energy_kcal: f.energy_kcal,
    protein_g: f.protein_g,
    carbohydrate_g: f.carbohydrate_g,
    fat_g: f.fat_g,
    fibre_g: f.fibre_g,
    standard_serving_grams: f.standard_serving_grams,
    serving_unit: 'g',
  }));
}

/**
 * Resolves a detected text label (e.g. from Gemini Vision) to the best matching food in catalog.
 */
export function resolveFoodAlias(label: string): FoodWithAliases | null {
  const norm = (label || '').trim().toLowerCase();
  if (!norm) return null;

  // 1. Exact match on alias
  for (const food of FOOD_CATALOG) {
    if (food.aliases.some((a) => a.toLowerCase() === norm)) {
      return food;
    }
  }

  // 2. Contains match on alias or names
  for (const food of FOOD_CATALOG) {
    if (food.aliases.some((a) => norm.includes(a.toLowerCase()) || a.toLowerCase().includes(norm))) {
      return food;
    }
    if (norm.includes(food.canonical_name.toLowerCase()) || food.canonical_name.toLowerCase().includes(norm)) {
      return food;
    }
    if (norm.includes(food.name_bn) || food.name_bn.includes(norm)) {
      return food;
    }
  }

  return null;
}

/**
 * Get single food by its UUID.
 */
export function getFoodById(id: string): FoodWithAliases | null {
  return FOOD_CATALOG.find((f) => f.id === id) || null;
}

